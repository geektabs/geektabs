const translateSingleHoliday = (name: string, language: string): string => {
  if (!language || language === 'English') return name;

  if (name.endsWith(' (Observed)')) {
    const base = name.slice(0, -' (Observed)'.length);
    const translatedBase = BASE_HOLIDAYS[base]?.[language] || base;
    return `${translatedBase}${OBSERVED_SUFFIX[language] || ' (Observed)'}`;
  }

  if (name.endsWith(' (Day 2)')) {
    const base = name.slice(0, -' (Day 2)'.length);
    const translatedBase = BASE_HOLIDAYS[base]?.[language] || base;
    return `${translatedBase}${DAY2_SUFFIX[language] || ' (Day 2)'}`;
  }

  return BASE_HOLIDAYS[name]?.[language] || name;
};

export const translateHolidayName = (rawName: string, language: string): string => {
  if (!rawName || !language || language === 'English') return rawName;
  return rawName
    .split(' / ')
    .map((segment) => translateSingleHoliday(segment.trim(), language))
    .join(' / ');
};
